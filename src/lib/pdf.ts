import { jsPDF } from "jspdf";
import { formatMoney, formatDate } from "./utils";

export interface InvoicePdfData {
  invoiceNumber: string;
  dueDate: Date | string;
  createdAt: Date | string;
  status: string;
  companyName: string;
  companyAddress?: string | null;
  companyEmail?: string | null;
  companyPhone?: string | null;
  customerName: string;
  customerEmail: string;
  customerAddress?: string | null;
  lineItems: Array<{
    description: string;
    quantity: number;
    unitPriceCents: number;
    totalCents: number;
  }>;
  subtotalCents: number;
  taxCents: number;
  totalCents: number;
  paidCents: number;
  currency: string;
  notes?: string | null;
}

export function generateInvoicePdf(data: InvoicePdfData): jsPDF {
  const doc = new jsPDF({
    orientation: "portrait",
    unit: "mm",
    format: "a4",
  });

  // Colors
  const darkGreen = "#1b4332";
  const gray = "#555555";
  const lightGray = "#f4f4f4";

  // Header
  doc.setFontSize(22);
  doc.setTextColor(darkGreen);
  doc.text(data.companyName.toUpperCase(), 20, 25);

  doc.setFontSize(9);
  doc.setTextColor(gray);
  if (data.companyAddress) doc.text(data.companyAddress, 20, 31);
  if (data.companyPhone) doc.text(`Phone: ${data.companyPhone}`, 20, 36);
  if (data.companyEmail) doc.text(`Email: ${data.companyEmail}`, 20, 41);

  // Invoice Title & Info (Right side)
  doc.setFontSize(20);
  doc.setTextColor(darkGreen);
  doc.text("INVOICE", 150, 25);

  doc.setFontSize(9);
  doc.setTextColor(gray);
  doc.text(`Invoice #: ${data.invoiceNumber}`, 150, 31);
  doc.text(`Issue Date: ${formatDate(data.createdAt)}`, 150, 36);
  doc.text(`Due Date: ${formatDate(data.dueDate)}`, 150, 41);
  doc.text(`Status: ${data.status}`, 150, 46);

  // Line Divider
  doc.setDrawColor(200, 200, 200);
  doc.line(20, 52, 190, 52);

  // Bill To
  doc.setFontSize(10);
  doc.setTextColor(darkGreen);
  doc.text("BILL TO:", 20, 60);

  doc.setFontSize(9);
  doc.setTextColor(gray);
  doc.text(data.customerName, 20, 66);
  if (data.customerAddress) doc.text(data.customerAddress, 20, 71);
  doc.text(data.customerEmail, 20, 76);

  // Table Header
  let y = 88;
  doc.setFillColor(235, 243, 238);
  doc.rect(20, y - 5, 170, 8, "F");

  doc.setFontSize(9);
  doc.setTextColor(darkGreen);
  doc.text("SERVICE / DESCRIPTION", 23, y);
  doc.text("QTY", 125, y, { align: "center" });
  doc.text("RATE", 150, y, { align: "right" });
  doc.text("TOTAL", 187, y, { align: "right" });

  // Table Rows
  y += 6;
  doc.setTextColor(gray);
  data.lineItems.forEach((item) => {
    // Multi-line wrap
    const descLines = doc.splitTextToSize(item.description, 95);
    doc.text(descLines, 23, y);
    doc.text(String(item.quantity), 125, y, { align: "center" });
    doc.text(formatMoney(item.unitPriceCents, data.currency), 150, y, { align: "right" });
    doc.text(formatMoney(item.totalCents, data.currency), 187, y, { align: "right" });

    const rowHeight = descLines.length * 5 + 3;
    y += rowHeight;
  });

  // Totals Box
  y += 5;
  doc.line(120, y, 190, y);
  y += 6;

  doc.text("Subtotal:", 145, y, { align: "right" });
  doc.text(formatMoney(data.subtotalCents, data.currency), 187, y, { align: "right" });

  if (data.taxCents > 0) {
    y += 6;
    doc.text("Tax:", 145, y, { align: "right" });
    doc.text(formatMoney(data.taxCents, data.currency), 187, y, { align: "right" });
  }

  y += 7;
  doc.setFontSize(11);
  doc.setTextColor(darkGreen);
  doc.text("Total Due:", 145, y, { align: "right" });
  doc.text(formatMoney(data.totalCents, data.currency), 187, y, { align: "right" });

  if (data.paidCents > 0) {
    y += 6;
    doc.setFontSize(9);
    doc.setTextColor("#16a34a");
    doc.text("Paid to Date:", 145, y, { align: "right" });
    doc.text(`-${formatMoney(data.paidCents, data.currency)}`, 187, y, { align: "right" });

    y += 6;
    doc.setFontSize(10);
    doc.setTextColor("#d97706");
    doc.text("Balance Due:", 145, y, { align: "right" });
    doc.text(formatMoney(Math.max(0, data.totalCents - data.paidCents), data.currency), 187, y, {
      align: "right",
    });
  }

  // Footer / Notes
  if (data.notes) {
    y = Math.max(y + 15, 230);
    doc.setFontSize(8);
    doc.setTextColor(gray);
    doc.text("PAYMENT TERMS & NOTES:", 20, y);
    doc.text(doc.splitTextToSize(data.notes, 170), 20, y + 5);
  }

  doc.setFontSize(7);
  doc.setTextColor("#999999");
  doc.text("Generated by PestPilot Field Management Software", 105, 285, { align: "center" });

  return doc;
}

